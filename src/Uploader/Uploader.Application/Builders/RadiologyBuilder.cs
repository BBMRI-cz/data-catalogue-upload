using System.Text.Json.Nodes;
using Uploader.Application.Json;
using Uploader.Domain;

namespace Uploader.Application.Builders;

/// <summary>Builds an <see cref="ImagingStudy"/> (with its modality-specific series) from a raw payload.</summary>
public sealed class RadiologyBuilder
{
    public ImagingStudy BuildImagingStudy(JsonObject payload)
    {
        var accessionNumber = RawJson.RequireString(payload, "accession_number");
        return new ImagingStudy
        {
            AccessionNumber = accessionNumber,
            SourceId = RawJson.ResolveSourceId(payload, accessionNumber),
            ImagingStudyIdentifier = payload.GetString("imaging_study_identifier"),
            BelongsToPerson = payload.GetString("belongs_to_person"),
            ImagingModality = payload.GetStringList("imaging_modality"),
            BodyRegion = payload.GetStringList("body_region"),
            ImagingProcedure = payload.GetStringList("imaging_procedure"),
            ReasonForImagingProcedure = payload.GetStringList("reason_for_imaging_procedure"),
            StudyStartDate = payload.GetString("study_start_date"),
            DicomSeriesCount = payload.GetInt("dicom_series_count"),
            DicomImagesCount = payload.GetInt("dicom_images_count"),
            AffiliatedInstitution = payload.GetString("affiliated_institution"),
            CtSeries = BuildCt(payload.GetObject("ct_series")),
            MrSeries = BuildMr(payload.GetObject("mr_series")),
            UsSeries = BuildUs(payload.GetObject("us_series")),
            DxSeries = BuildDx(payload.GetObject("dx_series")),
            MgSeries = BuildMg(payload.GetObject("mg_series")),
        };
    }

    private static CtSeries? BuildCt(JsonObject? p) => p is null ? null : new CtSeries
    {
        SourceId = RawJson.ResolveSourceId(p),
        SeriesIdentifier = p.GetString("series_identifier"),
        ImagingStudyIdentifier = p.GetString("imaging_study_identifier"),
