        SeriesStartDate = p.GetString("series_start_date"),
        BodyRegion = p.GetString("body_region"),
        Laterality = p.GetString("laterality"),
        ImagingDevice = p.GetString("imaging_device"),
        ManufacturerOfImagingDevice = p.GetString("manufacturer_of_imaging_device"),
        SoftwareVersion = p.GetString("software_version"),
        ColorSpace = p.GetString("color_space"),
        PixelSpacing = p.GetInt("pixel_spacing"),
        ImageType = p.GetString("image_type"),
        FileFormat = p.GetString("file_format"),
        FileSize = p.GetInt("file_size"),
        ImageWidth = p.GetInt("image_width"),
        ImageHeight = p.GetInt("image_height"),
        ImageDepth = p.GetInt("image_depth"),
        NumberOfChannels = p.GetInt("number_of_channels"),
        ChannelResolution = p.GetInt("channel_resolution"),
        CompressionMethod = p.GetString("compression_method"),
        CompressionQualityLabel = p.GetString("compression_quality_label"),
        AnnotationsAvailable = p.GetBool("annotations_available"),
        TubeVoltageKvp = p.GetInt("tube_voltage_kvp"),
        XRayTubeCurrentMa = p.GetInt("x_ray_tube_current_ma"),
        ExposureTimeMs = p.GetInt("exposure_time_ms"),
        SpiralPitchFactor = p.GetDouble("spiral_pitch_factor"),
        FilterType = p.GetString("filter_type"),
        ConvolutionKernel = p.GetString("convolution_kernel"),
        FieldOfView = p.GetDouble("field_of_view"),
        SliceThickness = p.GetDouble("slice_thickness"),
        ImagingInjection = p.GetString("imaging_injection"),
        NumberOfImagePlanes = p.GetInt("number_of_image_planes"),
    };

